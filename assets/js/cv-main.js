const cvLangBtn = document.getElementById('cv-lang-switch');
let currentCvLang = 'pt';

cvLangBtn.addEventListener('click', () => {
    currentCvLang = currentCvLang === 'pt' ? 'en' : 'pt';
    cvLangBtn.textContent = currentCvLang === 'pt' ? '🇺🇸 EN' : '🇧🇷 PT';

    const elements = document.querySelectorAll('[data-lang]');
    
    elements.forEach(el => {
        const key = el.getAttribute('data-lang');
        if (cvTranslations[currentCvLang][key]) {
            el.innerHTML = cvTranslations[currentCvLang][key];
        }
    });
});